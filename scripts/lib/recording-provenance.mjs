// Bind recording metadata to the preview that was loaded, before UI edits begin.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { createServer } from "node:http";
import {
  copyFileSync,
  existsSync,
  lstatSync,
  readFileSync,
  readdirSync,
  realpathSync,
  renameSync,
  rmSync,
  statSync,
  watch,
  writeFileSync,
} from "node:fs";
import { join, resolve, sep } from "node:path";
import { projectRoot } from "./browser.mjs";

const helper = "scripts/lib/recording-provenance.mjs";
const runtimeFile = /\.(?:py|js|mjs|html|css|glsl|svg)$/;
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");

export function recordingProvenance(recorder, { root = projectRoot } = {}) {
  root = realpathSync(root);
  const fixed = [recorder, helper, "scripts/lib/browser.mjs", "docs/gifs/showcases.json"];
  const trees = [
    ["niri_fx", runtimeFile],
    ["examples", /\.json$/],
  ];
  let changed, generated, loaded, server, origin;
  const responses = new Map();
  const watchers = [];

  function read(path) {
    const absolute = resolve(root, path);
    assert(
      !path.startsWith("/") && absolute.startsWith(root + sep),
      "Recording inputs must stay inside the checkout",
    );
    assert(
      lstatSync(absolute).isFile() && realpathSync(absolute) === absolute,
      "Recording inputs must be regular files: " + path,
    );
    return readFileSync(absolute);
  }

  function inventory() {
    const paths = [...fixed];
    function visit(folder, pattern) {
      for (const entry of readdirSync(join(root, folder), { withFileTypes: true })) {
        if (entry.name.startsWith(".") || entry.name === "__pycache__") continue;
        const path = folder + "/" + entry.name;
        assert(!entry.isSymbolicLink(), "Recording input cannot be a symlink: " + path);
        if (entry.isDirectory()) visit(path, pattern);
        else if (pattern.test(entry.name)) paths.push(path);
      }
    }
    for (const [folder, pattern] of trees) visit(folder, pattern);
    return Object.fromEntries([...new Set(paths)].sort().map((path) => [path, digest(read(path))]));
  }

  const initial = inventory();
  // Also reject edits that were reverted before the end-of-capture hash check.
  // Watches ignore generated bytecode and frames, and never keep a failed run alive.
  try {
    for (const [folder, pattern] of trees)
      watchers.push(
        watch(join(root, folder), { recursive: true, persistent: false }, (_event, filename) => {
          if (!filename || pattern.test(filename)) changed ||= folder + "/" + (filename || "?");
        }),
      );
    for (const path of fixed)
      watchers.push(watch(join(root, path), { persistent: false }, () => (changed ||= path)));
    for (const watcher of watchers)
      watcher.on("error", () => (changed ||= "recording input watcher"));
  } catch (error) {
    for (const watcher of watchers) watcher.close();
    throw error;
  }

  function unchanged() {
    if (changed) throw new Error("Recording inputs changed during capture: " + changed);
    const current = inventory();
    const difference = [...new Set([...Object.keys(initial), ...Object.keys(current)])].find(
      (path) => initial[path] !== current[path],
    );
    if (difference) throw new Error("Recording inputs changed during capture: " + difference);
    if (generated && digest(readFileSync(generated.path)) !== generated.sha256)
      throw new Error("Generated recording preview changed during capture");
  }

  function generate(page, arguments_ = []) {
    unchanged();
    generated = null;
    loaded = null;
    execFileSync("python3", ["-m", "niri_fx", "preview", ...arguments_, "--output", page], {
      cwd: root,
      stdio: "pipe",
    });
    unchanged();
    const bytes = readFileSync(page);
    const catalog = JSON.parse(
      bytes
        .toString("utf8")
        .match(/<script id="effect-catalog" type="application\/json">([\s\S]*?)<\/script>/)?.[1] ||
        "null",
    );
    assert(catalog && !catalog.connection, "Record only an offline, unauthenticated preview");
    assert.match(catalog.studio?.build || "", /^[0-9a-f]{12}$/);
    assert.equal(typeof catalog.studio.version, "string");
    generated = {
      path: resolve(page),
      bytes,
      sha256: digest(bytes),
      studio: { version: catalog.studio.version, build: catalog.studio.build },
    };
    loaded = null;
  }

  async function originalResource(browser) {
    const { frameTree } = await browser.rpc("Page.getResourceTree");
    const frame = frameTree.frame;
    assert.equal(frame.url, loaded.url, "Recording navigated away from its bound preview");
    assert.equal(frame.loaderId, loaded.loaderId, "Recording preview was reloaded during capture");
    const resource = await browser.rpc("Page.getResourceContent", {
      frameId: frame.id,
      url: frame.url,
    });
    const bytes = Buffer.from(resource.content, resource.base64Encoded ? "base64" : "utf8");
    assert.equal(digest(bytes), generated.sha256, "Loaded recording document differs from preview");
  }

  async function navigate(browser, options) {
    assert(generated, "Generate the recording preview before loading it");
    unchanged();
    if (!server) {
      server = createServer((request, response) => {
        const bytes = request.method === "GET" && responses.get(request.url);
        if (!bytes) return response.writeHead(404).end();
        response.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
        response.end(bytes);
      });
      await new Promise((accept, reject) => {
        server.once("error", reject);
        server.listen(0, "127.0.0.1", accept);
      });
      origin = "http://127.0.0.1:" + server.address().port;
    }
    const path = "/" + generated.sha256 + ".html";
    responses.set(path, generated.bytes);
    // file:// documents are not cached by Page.getResourceContent. Serve the
    // frozen bytes once so CDP can verify the original response, never a refetch.
    await browser.rpc("Network.enable");
    await browser.navigate(origin + path, options);
    const { frameTree } = await browser.rpc("Page.getResourceTree");
    loaded = { url: origin + path, loaderId: frameTree.frame.loaderId, browser };
    await originalResource(browser);
    unchanged();
  }

  async function finish(sources) {
    assert(loaded, "Load and bind the recording preview before publishing");
    await originalResource(loaded.browser);
    unchanged();
    return {
      sources: Object.fromEntries(
        [...new Set(sources)].map((path) => {
          assert(Object.hasOwn(initial, path), "Recording source was not snapshotted: " + path);
          return [path, initial[path]];
        }),
      ),
      capture: {
        schema: 1,
        preview_sha256: generated.sha256,
        inputs_sha256: digest(JSON.stringify(initial)),
        studio: { ...generated.studio },
        tool_sources: Object.fromEntries(
          [helper, "scripts/lib/browser.mjs"].map((path) => [path, initial[path]]),
        ),
      },
    };
  }

  async function publish({
    sources,
    encoded,
    destination,
    manifestPath,
    entry,
    requireExisting = false,
  }) {
    const provenance = await finish(sources);
    const bytes = statSync(encoded).size;
    assert(bytes > 1000, "Encoded recording must contain a complete GIF");
    assert.match(readFileSync(encoded).subarray(0, 6).toString("ascii"), /^GIF8[79]a$/);
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    assert(Array.isArray(manifest.clips), "Recording manifest must contain clips");
    const replacement = { ...entry, file: destination, bytes, ...provenance };
    const index = manifest.clips.findIndex((clip) => clip.file === destination);
    assert(!requireExisting || index >= 0, "Existing recording manifest row required");
    if (index < 0) manifest.clips.push(replacement);
    else manifest.clips[index] = replacement;

    // Prepare both outputs before replacing either. Keep raw evidence in artifacts
    // on failure, and restore the previous GIF if publishing its metadata fails.
    const stagedManifest = encoded + ".manifest.json";
    const previous = encoded + ".previous.gif";
    writeFileSync(stagedManifest, JSON.stringify(manifest, null, 2) + "\n", { flag: "wx" });
    unchanged();
    const hadPrevious = existsSync(destination);
    if (hadPrevious) copyFileSync(destination, previous);
    renameSync(encoded, destination);
    try {
      renameSync(stagedManifest, manifestPath);
    } catch (error) {
      try {
        renameSync(destination, encoded);
        if (hadPrevious) renameSync(previous, destination);
      } catch (rollbackError) {
        throw new AggregateError(
          [error, rollbackError],
          "Recording publication and rollback failed",
          { cause: rollbackError },
        );
      }
      throw error;
    }
    if (hadPrevious) rmSync(previous);
    return replacement;
  }

  async function close() {
    for (const watcher of watchers) watcher.close();
    if (server?.listening) {
      server.closeAllConnections();
      await new Promise((accept, reject) =>
        server.close((error) => (error ? reject(error) : accept())),
      );
    }
    server = null;
  }

  return { generate, navigate, finish, publish, close };
}
